def replace_table_body(text: str, header_marker: str, end_marker: str, rows, label: str) -> str:
    lines = text.split(NL)
    hits = [i for i, line in enumerate(lines) if line.startswith(header_marker)]
    if len(hits) != 1:
        raise SystemExit("update_d014: header anchor count %d for %s" % (len(hits), label))
    start = hits[0]
    tail = [i for i, line in enumerate(lines) if line.startswith(end_marker) and i > start]
    if not tail:
        raise SystemExit("update_d014: end anchor not found for " + label)
    end = tail[0]
    return NL.join(lines[:start] + list(rows) + lines[end:])


